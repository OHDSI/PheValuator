styler::style_pkg()
OhdsiRTools::checkUsagePackage("PheValuator")
OhdsiRTools::updateCopyrightYearFolder()
devtools::spell_check()

# Create arg functions (before docs so the manual and site include them):
# Arguments supplied by runPheValuatorAnalyses() (phenotype, analysisName, runDateTime, databaseId,
# exportFolder, and priorModelToUse for the evaluation cohort) are excluded.
# ParallelLogger::createArgFunction reads the INSTALLED package's help files, so install
# PheValuator and attach the installed copy (devtools::load_all() is not sufficient).
# Install into a temporary library from a separate process: installing over a copy that is already
# loaded in this session (e.g. by checkUsagePackage) corrupts its lazy-load database.
if ("PheValuator" %in% loadedNamespaces()) {
  try(pkgload::unload("PheValuator"), silent = TRUE)
  if ("PheValuator" %in% loadedNamespaces()) {
    unloadNamespace("PheValuator")
  }
}
argLib <- tempfile("PheValuatorArgLib")
dir.create(argLib)
status <- system2(file.path(R.home("bin"), "R"),
                  c("CMD", "INSTALL", "--no-test-load", paste0("--library=", shQuote(argLib)), shQuote(getwd())))
if (status != 0) {
  stop("Installing PheValuator into a temporary library failed")
}
.libPaths(c(argLib, .libPaths()))
library(PheValuator)
rCode <- c("# This file has been autogenerated. Do not change by hand. ")
rCode <- ParallelLogger::createArgFunction("createEvaluationCohort",
                                           excludeArgs = c("connectionDetails",
                                                           "cdmDatabaseSchema",
                                                           "oracleTempSchema",
                                                           "tempEmulationSchema",
                                                           "workDatabaseSchema",
                                                           "cohortDatabaseSchema",
                                                           "cohortTable",
                                                           "outFolder",
                                                           "evaluationCohortId",
                                                           "cdmVersion",
                                                           "phenotype",
                                                           "analysisName",
                                                           "runDateTime",
                                                           "databaseId",
                                                           "exportFolder",
                                                           "priorModelToUse"),
                                           rCode = rCode)
rCode <- ParallelLogger::createArgFunction("testPhenotypeAlgorithm",
                                           excludeArgs = c("connectionDetails",
                                                           "cdmDatabaseSchema",
                                                           "cohortDatabaseSchema",
                                                           "cohortTable",
                                                           "outFolder",
                                                           "evaluationCohortId",
                                                           "phenotype",
                                                           "analysisName",
                                                           "runDateTime",
                                                           "databaseId",
                                                           "exportFolder"),
                                           rCode = rCode)
writeLines(rCode, "R/CreateArgFunctions.R")
OhdsiRTools::formatRFile("R/CreateArgFunctions.R")
devtools::document()

